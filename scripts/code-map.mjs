/**
 * Writes docs/CODEMAP.md: every source file with the first sentence of its header comment, and every plan by title.
 * Run `npm run codemap` after adding, removing or re-describing a file; the PR check fails if the map is stale.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'docs', 'CODEMAP.md');

// What each folder holds, shown above its files.
const FOLDERS = [
  ['src', 'Entry point, router and service worker.'],
  ['src/app', 'The root layout and the error screen.'],
  ['src/routes', 'One component per screen (the hash route it serves is in src/router.tsx).'],
  ['src/components', 'Dialogs, panels and pieces shared by several screens.'],
  ['src/components/items', 'One card per item type (multiple choice, flashcard, definition, problem...), plus the editor.'],
  ['src/components/session', 'The study screen: the card session, browsing, the rail and glossary.'],
  ['src/store', 'Zustand stores: lectures, progress, the study log, settings. Everything saved on the device.'],
  ['src/schema', 'The .study.json format (Zod) and its parser.'],
  ['src/lib', 'Logic with no screen: scheduling, Learn steps, prompts handed to the AI, content checks, the tree, sync.'],
  ['src/styles', 'Design tokens (theme.css), global rules and their tests.'],
  ['sim', 'The study simulator (see .claude/skills/simulate and sim/FINDINGS.md).'],
  ['scripts', 'Command-line tools: screenshots, icons, course audit, this map.'],
  ['supabase/functions', 'Server code for push reminders (Deno, deployed to Supabase).'],
];

const SKIP = /(\.test\.|\.d\.ts$|__fixtures__)/;
const EXT = /\.(ts|tsx|mjs)$/;

function filesIn(dir) {
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) return [];
  return fs
    .readdirSync(abs, { withFileTypes: true })
    .filter((d) => d.isFile() && EXT.test(d.name) && !SKIP.test(d.name))
    .map((d) => `${dir}/${d.name}`)
    .sort((a, b) => a.localeCompare(b));
}

/** The first sentence of the file's leading comment, or null when it has none. */
function summary(file) {
  const src = fs.readFileSync(path.join(ROOT, file), 'utf8');
  const lines = src.split('\n');
  // The comment may sit after the imports, above the file's main export.
  let i = 0;
  for (;;) {
    const l = lines[i]?.trim();
    if (l === undefined) break;
    if (l === '' || l.startsWith('#!') || l.startsWith('///')) { i++; continue; }
    if (/^import\b/.test(l) || /^export \{.*\} from /.test(l)) {
      // Step over a multi-line import to its closing line.
      while (i < lines.length && !/(from\s+['"][^'"]+['"]|^import\s+['"][^'"]+['"]);?\s*$/.test(lines[i].trim())) i++;
      i++;
      continue;
    }
    break;
  }
  const text = [];
  if (lines[i]?.trim().startsWith('/*')) {
    for (; i < lines.length; i++) {
      const l = lines[i].replace(/^\s*\/\*\*?/, '').replace(/\*\/.*$/, '').replace(/^\s*\* ?/, '').trim();
      if (l === '' && text.length) break;
      if (l && !/^[=*-]{4,}$/.test(l)) text.push(l);
      if (lines[i].includes('*/')) break;
    }
  } else {
    for (; i < lines.length && lines[i].trim().startsWith('//'); i++) {
      const l = lines[i].replace(/^\s*\/\/\s?/, '').trim();
      if (l === '' && text.length) break;
      if (l) text.push(l);
    }
  }
  if (!text.length) return null;
  const joined = text.join(' ');
  const m = joined.match(/^.*?[.!?](?=\s|$)/);
  return (m ? m[0] : joined).replace(/\|/g, '\\|');
}

let out = `# Code map

Generated by \`npm run codemap\` from the first sentence of each file's header
comment. Do not edit by hand: change the file's header and run it again. The
pull-request check fails when this map is out of date.

Start here to find where something lives, then open the file. What each
feature is meant to do is in \`docs/EXPECTATIONS.md\`; the docs are listed in
\`docs/README.md\`.
`;

let missing = 0;
for (const [dir, about] of FOLDERS) {
  const files = filesIn(dir);
  if (!files.length) continue;
  out += `\n## ${dir}/\n\n${about}\n\n`;
  for (const f of files) {
    const s = summary(f);
    if (!s) missing++;
    out += `- \`${path.basename(f)}\`: ${s ?? '_no header yet_'}\n`;
  }
}
// Supabase functions live one folder down.
const fnDir = path.join(ROOT, 'supabase/functions');
if (fs.existsSync(fnDir)) {
  for (const fn of fs.readdirSync(fnDir).sort()) {
    const f = `supabase/functions/${fn}/index.ts`;
    if (!fs.existsSync(path.join(ROOT, f))) continue;
    const s = summary(f);
    if (!s) missing++;
    if (!out.includes('## supabase/functions/')) {
      out += `\n## supabase/functions/\n\n${FOLDERS.find(([d]) => d === 'supabase/functions')[1]}\n\n`;
    }
    out += `- \`${fn}/index.ts\`: ${s ?? '_no header yet_'}\n`;
  }
}

// Plans and records: each file's title, so a doc can be found by topic.
for (const [dir, about] of [
  ['docs/proposals', 'Plans, each with the options weighed and why one won (CLAUDE.md, "Plans").'],
  ['docs/archive', 'Finished records: past audits, briefs, prompts and the dated build log.'],
]) {
  const walk = (d) => fs.readdirSync(path.join(ROOT, d), { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(`${d}/${e.name}`) : e.name.endsWith('.md') ? [`${d}/${e.name}`] : []);
  if (!fs.existsSync(path.join(ROOT, dir))) continue;
  out += `\n## ${dir}/\n\n${about}\n\n`;
  for (const f of walk(dir).sort((a, b) => a.localeCompare(b))) {
    const title = fs.readFileSync(path.join(ROOT, f), 'utf8').match(/^# (.+)$/m)?.[1] ?? '_untitled_';
    out += `- \`${f.slice(dir.length + 1)}\`: ${title.replace(/\|/g, '\\|')}\n`;
  }
}

fs.writeFileSync(OUT, out);
console.log(`wrote docs/CODEMAP.md (${missing} files without a header)`);
